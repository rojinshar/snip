import { mkdir } from 'node:fs/promises';
import path from 'node:path';
import { parseArgs } from 'node:util';

import { UsageError, nonNegativeInt, positiveInt } from './cli-args.ts';
import {
  UNIMER_SUBSETS,
  type UnimerSubset,
  importUnimer,
  isUnimerSubset,
  writeManifest,
} from './importers/unimer.ts';

const BENCH_ROOT = path.resolve(import.meta.dirname, '..');

const USAGE = `Usage: npm run bench:import-unimer -- [options]

Samples UniMER-Test into a benchmark manifest. Download and extract the test set first;
see apps/bench/data/README.md.

Options:
  --source <dir>        Extracted UniMER-Test directory
                        (default: data/unimer-test/raw/UniMER-Test)
  --out <dir>           Where manifest.jsonl is written (default: data/unimer-test)
  --subsets <list>      Comma-separated: ${Object.keys(UNIMER_SUBSETS).join(', ')} (default: all)
  --per-subset <n>      Images sampled per subset (default: 25)
  --seed <n>            Sampling seed; same seed, same sample (default: 42)
  -h, --help            Show this help

Relative paths resolve against apps/bench.`;

const CLI_OPTIONS = {
  source: { type: 'string', default: 'data/unimer-test/raw/UniMER-Test' },
  out: { type: 'string', default: 'data/unimer-test' },
  subsets: { type: 'string', default: Object.keys(UNIMER_SUBSETS).join(',') },
  'per-subset': { type: 'string', default: '25' },
  seed: { type: 'string', default: '42' },
  help: { type: 'boolean', short: 'h', default: false },
} as const;

async function main(): Promise<void> {
  let values;
  try {
    ({ values } = parseArgs({ args: process.argv.slice(2), options: CLI_OPTIONS, strict: true }));
  } catch (error) {
    throw new UsageError(error instanceof Error ? error.message : String(error));
  }
  if (values.help) {
    console.log(USAGE);
    return;
  }

  const subsets = values.subsets.split(',').map((name) => name.trim());
  const unknown = subsets.filter((name) => !isUnimerSubset(name));
  if (unknown.length > 0) throw new UsageError(`Unknown subset(s): ${unknown.join(', ')}`);

  const sourceDir = path.resolve(BENCH_ROOT, values.source);
  const outDir = path.resolve(BENCH_ROOT, values.out);
  const perSubset = positiveInt('--per-subset', values['per-subset']);
  const seed = nonNegativeInt('--seed', values.seed);

  const { entries, reports } = await importUnimer({
    sourceDir,
    outDir,
    subsets: subsets as UnimerSubset[],
    perSubset,
    seed,
  });

  await mkdir(outDir, { recursive: true });
  const manifest = path.join(outDir, 'manifest.jsonl');
  await writeManifest(
    manifest,
    entries,
    `UniMER-Test sample: ${perSubset} per subset, seed ${seed}. Generated by import-unimer.`,
  );

  for (const report of reports) {
    console.log(
      `${report.subset} (${UNIMER_SUBSETS[report.subset]}): ${report.selected} selected of ` +
        `${report.available}, ${report.skipped} skipped (label missing or does not render)`,
    );
  }
  console.log(`\nWrote ${entries.length} entries to ${path.relative(process.cwd(), manifest)}`);
}

main().catch((error: unknown) => {
  if (error instanceof UsageError) {
    console.error(`error: ${error.message}\n\n${USAGE}`);
  } else if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
    console.error(`error: ${error.message}\nDid you download and extract UniMER-Test?`);
  } else {
    console.error(error);
  }
  process.exitCode = 1;
});
